#!/usr/bin/env bash
# The single enablement pass. Every unit file exists by now (packages in
# 10-packages.sh, shipped units in 20-overlay.sh), so each manifest's
# [services] and [[wants]] are applied here, and nowhere else.
#
# A preset file mirrors the same choices. systemd applies presets on a
# machine's first boot (enable-only), which would otherwise switch base-preset
# units such as thermald back on after a fresh install.
set -euo pipefail

PACKAGES=/ctx/build/packages
# shellcheck source=/dev/null
source /ctx/build/scripts/package-lib.sh

for manifest in "${PACKAGES}"/*.toml; do
	name="$(basename "${manifest}" .toml)"
	echo "::group:: Services: ${name}"
	enable_services_section "${manifest}" "${name}"
	disable_services_section "${manifest}" "${name}"
	link_wanted_units "${manifest}" "${name}"
	echo "::endgroup::"
done

echo "::group:: Presets"
write_presets() {
	local scope="$1" out="$2" manifest unit
	{
		echo "# Generated by build/40-services.sh from build/packages/*.toml."
		for manifest in "${PACKAGES}"/*.toml; do
			while IFS= read -r unit; do
				[[ -n "${unit}" ]] && echo "enable ${unit}"
			done < <("${READ_PKGS}" "${manifest}" services "${scope}" 2>/dev/null || true)
			if [[ "${scope}" == system ]]; then
				while IFS= read -r unit; do
					[[ -n "${unit}" ]] && echo "disable ${unit}"
				done < <("${READ_PKGS}" "${manifest}" services disabled 2>/dev/null || true)
			fi
		done
	} >"${out}"
}
install -d /usr/lib/systemd/system-preset /usr/lib/systemd/user-preset
write_presets system /usr/lib/systemd/system-preset/10-neptuno.preset
write_presets user /usr/lib/systemd/user-preset/10-neptuno.preset
cat /usr/lib/systemd/system-preset/10-neptuno.preset
echo "::endgroup::"
